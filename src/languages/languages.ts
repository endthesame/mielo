const languageNames = new Map(languages.map(({ code, name }) => [code, name]));

export function languageName(code: string): string {
  return languageNames.get(code) ?? code;
}

export function normalizeLanguageCode(code: string): string | null {
  const normalized = code.trim().toLowerCase();
  return /^[a-z]{2,3}$/.test(normalized) ? normalized : null;
}
